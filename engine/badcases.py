# -*- coding: utf-8 -*-
"""Bad Case 库：按本次参数生成触发条件、失效机理、监测信号与降级动作。"""


def _num(v, d=None):
    try:
        if v is None or v == "":
            return d
        return float(v)
    except (TypeError, ValueError):
        return d


def build(params, m, sim, mode):
    cases = []

    def add(name, trigger, why, impact, signal, fallback, need):
        cases.append({"name": name, "trigger": trigger, "why": why, "impact": impact,
                      "signal": signal, "fallback": fallback, "need": need})

    cap = m["hourly_capacity"]
    peak = m["demand_peak"]
    util = m["util"]
    spare = int(m["spare"] or 0)
    n = int(m["n_service"])
    cycle = m["cycle"]
    seats = m["seats"]

    add("客流预测偏低",
        f"实际高峰小时客流 > 预排 {peak:.0f} 人的 1.15 倍（即 > {peak * 1.15:.0f} 人/小时）",
        "预排班表按预测客流配置在运车辆，超预测部分没有对应运力，站台队列累积速度超过疏散速度。",
        f"利用率由 {util:.0%} 升至 {util * 1.15:.0%} 以上，"
        + ("已超 100%，出现旅客上不了车。" if util * 1.15 > 1 else "余量被吃尽，任一延误即形成滞留。"),
        "站点候车人数连续 2 个统计周期上升；车辆满载率达 100% 的班次占比上升；调度端收到的等待投诉增加。",
        f"启用备用车 {spare} 辆并暂停低负荷线路的加密；站台分批放行；同步向预约端收紧当日剩余额度。",
        "分时预约量与实际入园量的偏差记录；站点计数设备")

    add("客流预测偏高",
        f"实际高峰小时客流 < 预排的 0.7 倍（即 < {peak * 0.7:.0f} 人/小时）",
        "按预测投放的车辆无人可载，空驶与站台排队同时出现，单位客流成本上升。",
        f"满载率降至 {util * 0.7:.0%} 以下，空驶里程上升，司机工时被无效占用。",
        "连续 2 小时满载率 < 50%；车辆在起点站排队等客；单公里载客量下降。",
        "按 15 分钟粒度阶梯减车，优先减短途区间车；减下的车转为备用或安排补能维保；不得一次性大幅减车造成反弹滞留。",
        "历史同期的实际客流分布；分钟级闸机数据")

    add("局部站点突发大客流",
        f"单站 15 分钟内候车人数 ≥ {int(seats * 2)} 人（约 2 车容量），且站点间不均衡度显著上升",
        "全线平均口径的排班无法响应单点积压；车辆按固定间隔到达，但该站单班可载人数不足以清空队列。",
        "该站候车时间快速超过 30 分钟，并向相邻站点传导；返程端可能出现对流空驶。",
        "单站候车人数曲线突变；该站上车人数占全线比例由常态跃升；GPS 显示车辆在该站停靠时间延长。",
        f"从就近站点空车直放（空驶里程可控时优先）；开行该站至主要下车点的区间车；站务员现场分批引导至相邻站点。",
        "站点级实时计数；车辆实时位置与载客状态；可折返站点清单")

    lost_cap = cap - cap * max(1, m["available"] - 2) / max(1, m["available"])
    old_margin = max(0.0, cap - peak)
    new_margin = max(0.0, cap - lost_cap - peak)
    if cap - lost_cap < peak:
        fault_impact = (f"小时有效运力由 {cap:.0f} 降至 {cap - lost_cap:.0f} 人/小时，"
                        f"由余量 {old_margin:.0f} 转为缺口 {peak - (cap - lost_cap):.0f} 人/小时。")
    else:
        fault_impact = (f"小时有效运力由 {cap:.0f} 降至 {cap - lost_cap:.0f} 人/小时，"
                        f"余量由 {old_margin:.0f} 收窄至 {new_margin:.0f} 人/小时。")

    add("车辆故障或可用车减少",
        f"可用车由 {m['available']:.0f} 辆降至 {max(1, m['available'] - 2):.0f} 辆（故障、事故、补能占用）",
        "运力按可用车数的线性函数下降，且故障通常发生在高负荷时段；备用车不足时缺口直接暴露在站台。",
        fault_impact,
        f"备用车调用次数；车辆在线率低于 {m['available'] / max(1, m['available'] + spare):.0%}；维修工单集中出现。",
        "立即调用备用车并延后非必要维保；缩短单车间隔至下限；必要时启用区间车保住主客流段。",
        "车辆状态实时回传；备用车停放位置与到场时间")

    add("天气导致循环时间增加",
        f"循环时间由 {cycle:g} 分钟升至 {m['cycle_rain']:g} 分钟（雨天/湿滑限速）",
        "运力与循环时间成反比，同样的车数在同样时间内完成的班次减少，且上下客时间同步变长。",
        f"小时有效运力由 {cap:.0f} 降至 {m['cap_rain']:.0f} 人/小时，缺口 {max(0, m['gap_rain']):.0f} 人/小时。",
        "实际循环时间与计划偏差 > 15%；区间行驶时间整体上移；司机上报路面湿滑或能见度下降。",
        "按天气档位下调计划运力并提前公告；缩短发车间隔但保留站台排队空间；必要时减少班次密度、改为满员发车并加强站台秩序。",
        "分天气类型的循环时间实测系数；道路限速与封闭信息")

    add("道路封闭或拥堵",
        f"主通道单向通行中断或绕行导致循环时间增加 ≥ 30%（{cycle * 1.3:.0f} 分钟以上）",
        "拓扑改变使原有点对点排班失效，车辆无法按计划回到起点，间隔被拉长且不可预测。",
        "运力下降 20% 以上；下游站点出现空档；返程旅客积压。",
        "GPS 轨迹偏离常规路径；区间行程时间告警；现场上报的封路或事故信息。",
        "切换到预设绕行方案并重算循环时间；暂停短线车、集中车辆保主线；在封闭点设置接驳或步行引导；同步向预约端提示。",
        "可绕行路径与通行能力；封路时的接驳车辆与人员")

    add("数据中断、延迟或错误",
        f"数据延迟 > {max(15, _num(params.get('f_latency'), 30)):g} 分钟，或站点计数缺失率 > 20%",
        "滚动调度依赖连续数据流；数据中断后模型仍按旧状态输出建议，可能把车调往已经缓解的站点。",
        "调度建议与实际需求错位；出现'车到无人、人等多时'的双向损失；决策失去可追溯性。",
        "数据刷新间隔超时；缺失率突增；上报值与 GPS 推算值偏差 > 30%。",
        "自动降级为固定班次 + 对讲机人工核实；以现场站务员口报为准；恢复后先做 30 分钟一致性校验再启用建议。",
        "数据质量监控与门限；人工核验流程；降级后的班表模板")

    drv_support = int(m["driver_avail_hours"] // m["op_hours"]) if m["op_hours"] else 0
    if drv_support >= n:
        drv_impact = (f"司机工时最多支撑约 {drv_support} 辆车，当前计划 {n} 辆，加车空间仅 {drv_support - n} 辆；"
                      "一旦站务员缺岗，指令无人组织，站台秩序风险上升。")
    else:
        drv_impact = (f"司机工时最多支撑约 {drv_support} 辆车，低于计划的 {n} 辆，"
                      f"约 {n - drv_support} 辆车实际无法开出；站台秩序风险上升。")

    add("车辆可调但司机或现场人员不足",
        f"所需司机工时 {m['driver_need_hours']:.0f} 人·小时接近可提供 {m['driver_avail_hours']:.0f} 人·小时，或站务员缺岗 > 1 人/站点",
        "加车方案停留在纸面：车辆在停车场，司机已到工时上限或在途，站台也无人组织排队。",
        drv_impact,
        "司机工时接近上限；加班申请集中；站台上车秩序混乱、投诉上升。",
        "不延长工时，改为缩短间隔内可完成的班次、启用大容量车型、组织站台分批放行；向相邻线路临时借调司机（须符合资质与工时规定）。",
        "司机排班与工时台账；站务员到岗表；可借调人员名单")

    add("多个站点同时出现需求高峰",
        "≥ 3 个站点的候车人数同时超过阈值，且可用车不足以同时覆盖",
        "车辆是共享资源，单点加车必然抽走其他站点的运力；多点同时高峰时任何逐点响应都会互相抵消。",
        "整体候车时间上升，调度动作频繁但净收益接近零；司机疲劳与违章风险上升。",
        "多站点同时触发告警；调车指令频次上升而平均候车不降；车辆空驶里程上升。",
        "放弃逐点加车，改为全局降低发车间隔并保主线；启用区间车隔离主客流段；对次要站点采用预约或分批引导。",
        "多点告警的关联分析；全局运力调度规则；站点优先级清单")

    add("调车导致其他线路服务下降",
        "从 A 线抽调车辆后，A 线高峰小时利用率 > 95% 或候车时间上升 > 30%",
        "运力不是凭空增加的，调车只是把缺口转移；被抽调线路往往正是次高峰线路。",
        "缺口从主站转移到次站，整体满意度未必提升，问题被掩盖。",
        "被抽调线路的候车与滞留指标恶化；跨线调车频次；投诉地点迁移。",
        "限制单线抽调比例（建议 ≤ 20%）；调车后 30 分钟内复核被抽调线路指标；必要时改为缩短间隔而非调车。",
        "线路间运力余量的实时视图；调车影响评估规则")

    add("满载率提高但候车时间与安全风险上升",
        f"以满载率 ≥ 95% 为目标的排班使平均候车时间上升，或站台积压超过 {int(seats * 1.5)} 人",
        "压间隔、减班次看似提高装载效率，实际是把等待成本转嫁给旅客，并放大站台的安全风险。",
        "平均候车与 P90 候车同时上升；站台拥挤度上升，上下客时间延长，反过来又拉长循环时间。",
        "满载率上升而候车时间同步上升；站台拥挤度告警；上下客耗时增加。",
        "设定满载率上限（建议 ≤ 90%）与候车时间上限（建议 P90 ≤ 20 分钟）双约束；任一越界即回到上一档排班。",
        "站台拥挤度观测；上下客耗时实测；旅客等候容忍度调查")

    return {
        "cases": cases,
        "note": "触发阈值为基于本次参数的分析建议值，未经本景区历史数据校准；上线前应用实际台账回归阈值。",
    }
