# -*- coding: utf-8 -*-
"""把四幕在线快照固化成一个可双击打开的离线数据文件。

用法：
    python tools/build_snapshot.py
输出：
    static/demo_snapshot.js  ->  window.DISPATCH_BOOT
"""
import json
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import config
from app import all_projects, build_snapshot
from storage import now_iso

SCENES = ["eve", "morning", "noon", "evening"]


def main():
    snaps = {}
    for scene_id in SCENES:
        snap = build_snapshot(config.DEMO_PROJECT, "dispatcher", scene_id, source="offline")
        snap["meta"]["source"] = {
            "mode": "offline",
            "label": "离线快照",
            "note": "四幕演示数据已固化；双击 html 即可断网演示。",
        }
        snaps[scene_id] = snap
        print("  built", scene_id, "cards", len(snap.get("desk", {}).get("cards", [])),
              "tasks", len(snap.get("driver", {}).get("tasks", [])))

    boot = {
        "default_project": config.DEMO_PROJECT,
        "default_scene": "morning",
        "projects": all_projects(),
        "snapshots": snaps,
        "generated": now_iso(),
        "source": "离线快照 · 四幕 · 九寨沟标定样本",
    }

    target = config.STATIC / "demo_snapshot.js"
    payload = "/* generated by tools/build_snapshot.py · 请勿手改 */\n" \
              "window.DISPATCH_BOOT = " + json.dumps(boot, ensure_ascii=False, separators=(",", ":")) + ";\n"
    target.write_text(payload, encoding="utf-8")
    print("wrote", target, round(target.stat().st_size / 1024, 1), "KB")
    print("generated", boot["generated"])


if __name__ == "__main__":
    main()
